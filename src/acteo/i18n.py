_active_locale: str = _DEFAULT_LOCALE


def normalize_locale(locale: str | None) -> str:
    """Return a supported locale or fall back to English."""
    candidate = (locale or _DEFAULT_LOCALE).strip().lower()
    return candidate if candidate in SUPPORTED_LOCALES else _DEFAULT_LOCALE


def get_locale() -> str:
    """Return the current active locale."""
    return _active_locale


def set_locale(locale: str | None) -> str:
    """Set the active locale and return the normalized value."""
    global _active_locale
    normalized = normalize_locale(locale)
    _active_locale = normalized
    return normalized


def t(key: str, *, locale: str | None = None) -> str:
    """Return the translated value for a key, falling back to English."""
    active_locale = normalize_locale(locale if locale is not None else _active_locale)
    translations = _TRANSLATIONS.get(active_locale, _TRANSLATIONS[_DEFAULT_LOCALE])
    return translations.get(key, _TRANSLATIONS[_DEFAULT_LOCALE].get(key, key))
